def _location_label(location: dict) -> str:
    if "attachment_name" in location:
        suffix = f", страница {location['page']}" if "page" in location else ""
        return f"вложение {location['attachment_name']}{suffix}"
    if "page" in location:
        return f"страница {location['page']}"
    if "sheet" in location:
        return f"лист {location['sheet']}"
    if "slide" in location:
        return f"слайд {location['slide']}"
    return str(location.get("label", "фрагмент"))


def build_prompt(question: str, history: list[dict], citations: list[dict]) -> str:
    context = "\n\n".join(
        f"[{number}] {' → '.join(str(item.get('classification', {}).get(key)) for key in ('insurer', 'insurance_kind', 'product') if item.get('classification', {}).get(key)) or 'Нераспределено'}; "
        f"{item['filename']}, {_location_label(item['location'])}:\n{item.get('excerpt', item.get('text', ''))}"
        for number, item in enumerate(citations, 1)
    )
    previous = "\n".join(
        f"{message['role']}: {message['content']}" for message in history[-8:]
    )
    return (
        f"ИСТОЧНИКИ:\n{context or '(нет релевантных источников)'}"
        f"\n\nИСТОРИЯ:\n{previous}\n\nВОПРОС: {question}"
    )
